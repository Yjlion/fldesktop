#!/usr/bin/env python3
"""Writes apps/fl-settings/settings_index.inc: the labels of the controls on
each fl-settings page, for searching across pages. The labels are kept as in
the source (the gettext msgids); fl-settings translates and cleans them. Run it after changing a
page; tests/settings-index-check.sh says when it is out of date.
usage: settings-index.py [--check]"""
import os, re, sys

top = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sdir = os.path.join(top, "apps", "fl-settings")
cm = open(os.path.join(sdir, "CMakeLists.txt")).read()
pages = re.findall(r"^fld_settings_page\((\w+)\s+([^\s)]+)", cm, re.M)

ctor = re.compile(r'new\s+(?:fld::)?(?:Fl_\w+|\w*Button|\w*Switch|\w*Slider|\w*Choice|\w*Input|\w*Box)\s*\(([^;]*?)\)\s*;', re.S)
setl = re.compile(r'(?:->|\.)(?:label|copy_label)\(\s*(?:_\(\s*)?"((?:[^"\\]|\\.)+)"\s*\)')
# the page helpers: f.row("Speed:"), f.heading("Pointer"), check(f, "Natural scrolling")...
section = re.compile(r'(?:\.row|\brow_label|\.heading|\bcheck|\b(?!fl_)\w+_choice)\s*\([^;"]*?"((?:[^"\\]|\\.)+)"')
lit = re.compile(r'"((?:[^"\\]|\\.)+)"')

def clean(s):
    s = s.replace("\\n", " ").replace('\\"', '"')
    s = re.sub(r"&(?=\w)", "", s)  # a shortcut letter's marker
    s = re.sub(r"@[^ ]*", "", s).strip()
    s = s.rstrip(":").rstrip("…").rstrip(".").strip()
    return s

def good(s):
    return 3 <= len(s) <= 60 and re.search(r"[A-Za-z]{3}", s) and "%" not in s and not s.startswith(("/", "-")) \
        and not re.fullmatch(r"[a-z0-9_.-]+", s)  # identifiers, file names

rows = []
# a page built from a shared view names its source: "// settings-index: also <path from the top>"
also = re.compile(r"^//\s*settings-index:\s*also\s+(\S+)", re.M)
for pid, f in pages:
    src = open(os.path.join(sdir, f)).read()
    for extra in also.findall(src):
        src += open(os.path.join(top, extra)).read()
    found = []
    for m in ctor.finditer(src):
        for l in lit.findall(m.group(1)):
            found.append(l)
    found += setl.findall(src) + section.findall(src)
    seen = set()
    for l in found:
        c = clean(l)
        if good(c) and c.lower() not in seen:
            seen.add(c.lower())
            rows.append((pid, l))  # the source text: translated at run time

def esc(s):
    return s  # already a C string literal's contents

out = ["// generated by tools/settings-index.py: the labels on the settings pages, for search", ""]
out += ['{"%s", "%s"},' % (p, esc(l)) for p, l in rows]
text = "\n".join(out) + "\n"
path = os.path.join(sdir, "settings_index.inc")
if "--check" in sys.argv:
    have = open(path).read() if os.path.exists(path) else ""
    if have != text:
        print("settings_index.inc is out of date: run tools/settings-index.py")
        sys.exit(1)
    print("settings index: %d labels on %d pages, up to date" % (len(rows), len(pages)))
else:
    open(path, "w").write(text)
    print("%d labels on %d pages written to %s" % (len(rows), len(pages), path))
